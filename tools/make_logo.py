#!/usr/bin/env python3
"""Generates the WHDSelector logo: chrome letters in an 80s/90s demoscene
style (blue-white-gold chrome, red outline, black background).

Writes tools/logo_preview.png and src/gui/logo_data.c (16 colours,
interleaved bitplanes = ILBM BODY layout for MUI's Bodychunk class).

Run in Docker:
  docker run --rm -v "$PWD:/work" -w /work alpine:3.20 sh -c \
    "apk add -q python3 py3-pillow font-dejavu && python3 tools/make_logo.py"
"""
from PIL import Image, ImageDraw, ImageFont, ImageFilter, ImageChops

TEXT = "WHDSelector"
W, H = 400, 64            # width must be a multiple of 16 (BODY rows)
DEPTH = 4                 # 16 colours
FONT = "/usr/share/fonts/dejavu/DejaVuSans-BoldOblique.ttf"


def text_mask():
    """Text rendered big, then squeezed vertically for a blocky look."""
    font = ImageFont.truetype(FONT, 120)
    probe = Image.new("L", (1, 1))
    x0, y0, x1, y1 = ImageDraw.Draw(probe).textbbox((0, 0), TEXT, font=font)
    big = Image.new("L", (x1 - x0 + 20, y1 - y0 + 20), 0)
    ImageDraw.Draw(big).text((10 - x0, 10 - y0), TEXT, font=font, fill=255)
    big = big.crop(big.getbbox())
    # Fit inside the logo with room for the outline and shadow.
    tw, th = W - 24, H - 18
    return big.resize((tw, th), Image.LANCZOS).point(lambda v: 255 if v > 110 else 0)


def lerp(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


def chrome_gradient(h):
    """Classic chrome: dark blue sky, white horizon, dark line, gold ground."""
    stops = [
        (0.00, (10, 30, 110)),
        (0.30, (90, 160, 255)),
        (0.48, (240, 250, 255)),
        (0.52, (40, 20, 50)),
        (0.62, (150, 70, 20)),
        (0.85, (250, 190, 70)),
        (1.00, (255, 245, 200)),
    ]
    rows = []
    for y in range(h):
        t = y / max(1, h - 1)
        for i in range(len(stops) - 1):
            t0, c0 = stops[i]
            t1, c1 = stops[i + 1]
            if t0 <= t <= t1:
                rows.append(lerp(c0, c1, (t - t0) / (t1 - t0)))
                break
    return rows


def build():
    mask = text_mask()
    tw, th = mask.size
    ox, oy = (W - tw) // 2, (H - th) // 2 - 2

    full = Image.new("L", (W, H), 0)
    full.paste(mask, (ox, oy))

    img = Image.new("RGB", (W, H), (0, 0, 0))

    # Drop shadow (dark blue), offset down-right.
    shadow = ImageChops.offset(full.filter(ImageFilter.MaxFilter(5)), 4, 4)
    img.paste((20, 20, 70), (0, 0), shadow)

    # Outer dark-red edge and red outline.
    img.paste((110, 0, 0), (0, 0), full.filter(ImageFilter.MaxFilter(7)))
    img.paste((230, 20, 20), (0, 0), full.filter(ImageFilter.MaxFilter(5)))

    # Chrome fill, gradient over the letter height.
    grad = chrome_gradient(th)
    fill = Image.new("RGB", (W, H))
    px = fill.load()
    for y in range(H):
        c = grad[min(th - 1, max(0, y - oy))]
        for x in range(W):
            px[x, y] = c
    img.paste(fill, (0, 0), full)

    # Thin white highlight on the upper left edges of the letters.
    edge = ImageChops.subtract(full, ImageChops.offset(full, 1, 1))
    img.paste((255, 255, 255), (0, 0), edge)
    return img


def to_planar(img):
    """Quantise to 16 colours with black as colour 0; return (palette, body)."""
    q = img.quantize(colors=1 << DEPTH, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[: 3 * (1 << DEPTH)]
    pal += [0] * (3 * (1 << DEPTH) - len(pal))
    colours = [tuple(pal[i * 3: i * 3 + 3]) for i in range(1 << DEPTH)]

    # Make the darkest colour index 0 (background).
    darkest = min(range(len(colours)), key=lambda i: sum(colours[i]))
    order = [darkest] + [i for i in range(len(colours)) if i != darkest]
    remap = {old: new for new, old in enumerate(order)}
    colours = [colours[i] for i in order]
    data = [remap[v] for v in q.getdata()]

    row_bytes = ((W + 15) // 16) * 2
    body = bytearray()
    for y in range(H):
        row = data[y * W:(y + 1) * W]
        for plane in range(DEPTH):
            for bx in range(row_bytes):
                byte = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    if x < W and (row[x] >> plane) & 1:
                        byte |= 0x80 >> bit
                body.append(byte)
    preview = Image.new("RGB", (W, H))
    preview.putdata([colours[v] for v in data])
    return colours, bytes(body), preview


def write_c(colours, body, path):
    with open(path, "w") as f:
        f.write("/* Generated by tools/make_logo.py - do not edit. */\n")
        f.write('#include <exec/types.h>\n#include "gui/logo_data.h"\n\n')
        f.write("const ULONG logo_colors[%d] = {\n" % (3 * len(colours)))
        for r, g, b in colours:
            f.write("    0x%08lX, 0x%08lX, 0x%08lX,\n" % (r * 0x01010101, g * 0x01010101, b * 0x01010101))
        f.write("};\n\nconst UBYTE logo_body[%d] = {\n" % len(body))
        for i in range(0, len(body), 16):
            f.write("    " + ", ".join("0x%02X" % b for b in body[i:i + 16]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    image = build()
    colours, body, preview = to_planar(image)
    preview.resize((W * 2, H * 2), Image.NEAREST).save("tools/logo_preview.png")
    write_c(colours, body, "src/gui/logo_data.c")
    print("logo %dx%dx%d, body %d bytes" % (W, H, DEPTH, len(body)))
